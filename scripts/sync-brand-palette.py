"""Export Servicios' runtime palette to the public website and local brand pack.

Run from any directory; --check detects drift without writing files.
Never reads or writes the external generator.
"""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]
NAMES = ('green', 'green-dark', 'green-deep', 'paper', 'mint', 'ink', 'muted', 'line')


def palette():
    source = (ROOT / 'mock-servicios/styles.css').read_text(encoding='utf-8')
    return {name: re.search(r'--' + name + r':\s*(#[0-9a-fA-F]{6})\b', source)[1].lower()
            for name in NAMES}


def outputs():
    colors = palette()
    aliases = {
        'surface': 'paper', 'surface-container-low': 'mint',
        'surface-container-highest': 'line', 'on-surface': 'ink',
        'on-surface-variant': 'muted', 'primary': 'green-dark',
        'primary-container': 'green-deep', 'primary-fixed': 'mint',
        'secondary-container': 'mint', 'on-secondary-fixed-variant': 'muted',
        'outline-variant': 'line', 'brand': 'green',
    }
    css = '/* Generated by scripts/sync-brand-palette.py from mock-servicios/styles.css. */\n'
    # The existing admin document keeps all of its original inherited tokens.
    css += ':root:not(:has([data-admin-shell="true"])) {\n'
    css += ''.join(f'  --{k}: {v};\n' for k, v in colors.items())
    css += ''.join(f'  --{k}: var(--{v});\n' for k, v in aliases.items())
    css += '  --ghost-border: color-mix(in srgb, var(--line) 65%, transparent);\n}\n'
    result = {
        ROOT / 'frontend/app/brand-tokens.css': css,
        ROOT / 'branding/palette.json': json.dumps(colors, indent=2) + '\n',
    }
    config_path = ROOT / 'branding/briff-local/CONFIG_MARCA.json'
    if config_path.exists():
        config = json.loads(config_path.read_text(encoding='utf-8'))
        config['colors'] = {role: colors[token].upper() for role, token in {
            'deep': 'green-deep', 'primary': 'green', 'mint': 'mint',
            'paper': 'paper', 'accent': 'mint',
        }.items()}
        config['logoRule']['lightDefault'] = colors['green'].upper()
        config['logoConfigs']['light']['color'] = colors['green'].upper()
        for variant in config['logoConfigs']['light']['variants'].values():
            variant['color'] = colors['green'].upper()
        result[config_path] = json.dumps(config, ensure_ascii=False, indent=2) + '\n'
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    if drift:
        raise SystemExit('Palette drift: ' + ', '.join(drift))
    print('Servicios palette: ' + ('verified' if args.check else 'exported'))
